#!/usr/bin/env node
'use strict';

// Builds the Max artefacts from the sources:
//   max/organic.js      engine (bundled) + max/src/adapter.js, loaded by [v8]
//   max/organic.maxpat  the device patcher
//   max/Organic.amxd    the same patcher as a MIDI Effect file (experimental)
//
//   node tools/build.js          write the files
//   node tools/build.js --check  exit 1 if the committed files are stale

const fs = require('fs');
const path = require('path');
const { bundle } = require('./bundle');
const { build: buildPatch, amxd } = require('./maxpat');

const ROOT = path.join(__dirname, '..');

function buildAll() {
  const { VERSION } = require('../engine');
  const eng = bundle(ROOT, path.join(ROOT, 'engine', 'index.js'), 'OrganicEngine');
  const adapter = fs.readFileSync(path.join(ROOT, 'max', 'src', 'adapter.js'), 'utf8');
  const header = [
    '// organic.js: GENERATED by tools/build.js. Do not edit; change engine/ or max/src/adapter.js',
    '// and run `npm run build`.',
    `// engine ${VERSION}; modules: ${eng.modules.join(', ')}`,
    '',
  ].join('\n');
  const script = header + eng.source + '\n// ==== max/src/adapter.js\n' + adapter;
  const patch = JSON.stringify(buildPatch({ scriptName: 'organic.js' }), null, '\t') + '\n';
  return {
    'max/organic.js': script,
    'max/organic.maxpat': patch,
    'max/Organic.amxd': amxd(patch),
  };
}

function main(argv) {
  const out = buildAll();
  const check = argv.includes('--check');
  let stale = 0;
  for (const rel of Object.keys(out)) {
    const file = path.join(ROOT, rel);
    const data = out[rel];
    const current = fs.existsSync(file) ? fs.readFileSync(file) : null;
    const same = current && Buffer.compare(current, Buffer.from(data)) === 0;
    if (check) {
      if (!same) {
        stale++;
        process.stderr.write(`stale: ${rel}\n`);
      }
    } else if (!same) {
      fs.writeFileSync(file, data);
      process.stderr.write(`wrote ${rel}\n`);
    }
  }
  if (check && stale) {
    process.stderr.write('run `npm run build`\n');
    process.exit(1);
  }
}

if (require.main === module) main(process.argv.slice(2));

module.exports = { buildAll };
