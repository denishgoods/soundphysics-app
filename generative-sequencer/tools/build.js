#!/usr/bin/env node
'use strict';

// Builds the Max artefacts from the sources:
//   max/organic.js      engine (bundled) + max/src/adapter.js, loaded by [v8]
//   max/organic.maxpat  the device patcher
//   max/Organic.amxd    the same patcher as a MIDI Effect file (experimental)
//
//   node tools/build.js          write the files
//   node tools/build.js --check  exit 1 if the committed files are stale

const fs = require('fs');
const path = require('path');
const { bundle } = require('./bundle');
const { build: buildPatch, amxd } = require('./maxpat');

const ROOT = path.join(__dirname, '..');

function buildAll() {
  const { VERSION } = require('../engine');
  const eng = bundle(ROOT, path.join(ROOT, 'engine', 'index.js'), 'OrganicEngine');
  const adapter = fs.readFileSync(path.join(ROOT, 'max', 'src', 'adapter.js'), 'utf8');
  const header = [
    '// organic.js: GENERATED by tools/build.js. Do not edit; change engine/ or max/src/adapter.js',
    '// and run `npm run build`.',
    `// engine ${VERSION}; modules: ${eng.modules.join(', ')}`,
    '',
  ].join('\n');
  const script = header + eng.source + '\n// ==== max/src/adapter.js\n' + adapter;
  const patch = JSON.stringify(buildPatch({ scriptName: 'organic.js' }), null, '\t') + '\n';
  const out = {
    'max/organic.js': script,
    'max/organic.maxpat': patch,
    'max/Organic.amxd': amxd(patch),
  };
  for (const ex of EXAMPLES) out['examples/' + ex.file] = renderExample(ex);
  out['preview/organic-preview.html'] = previewPage(true);
  return out;
}

// The preview page: engine + kit + MIDI writer bundled into one HTML file.
// standalone=true gives a complete document for opening locally; false gives
// the body fragment the Artifact publisher wraps itself.
function previewPage(standalone) {
  const lib = bundle(ROOT, path.join(ROOT, 'preview', 'src', 'index.js'), 'OrganicPreviewLib');
  const app = fs.readFileSync(path.join(ROOT, 'preview', 'src', 'app.js'), 'utf8');
  const page = fs.readFileSync(path.join(ROOT, 'preview', 'src', 'page.html'), 'utf8');
  const body = page
    .replace('/*__BUNDLE__*/', () => '\n// GENERATED by tools/build.js from engine/, cli/lib/ and preview/src/. Do not edit.\n' + lib.source)
    .replace('/*__APP__*/', () => '\n' + app);
  if (!standalone) return body;
  const split = body.indexOf('<div class="wrap">');
  return (
    '<!doctype html>\n<html lang="en">\n<head>\n<meta charset="utf-8">\n' +
    '<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">\n' +
    body.slice(0, split) +
    '</head>\n<body>\n' +
    body.slice(split) +
    '</body>\n</html>\n'
  );
}

// Example performances to audition. The device plays exactly these when
// started from bar 1 with the same settings and tempo.
const EXAMPLES = [
  { file: 'organic-defaults-seed1-120bpm.mid', bpm: 120, params: { seed: 1 } },
  { file: 'organic-loose-seed7-96bpm.mid', bpm: 96, params: { seed: 7, looseness: 70, drift: 60, swing: 45, ghosts: 60 } },
  { file: 'organic-tight-seed3-124bpm.mid', bpm: 124, params: { seed: 3, looseness: 10, drift: 10, swing: 0, memory: 85, breath: 30 } },
  { file: 'organic-breathing-seed12-100bpm.mid', bpm: 100, params: { seed: 12, density: 45, breath: 100, memory: 50 } },
  { file: 'irregular-defaults-seed1-120bpm.mid', bpm: 120, params: { seed: 1, mode: 1 } },
  { file: 'irregular-shifting-seed3-110bpm.mid', bpm: 110, params: { seed: 3, mode: 1, looseness: 80 } },
  { file: 'mathematical-polymeter-seed2-118bpm.mid', bpm: 118, params: { seed: 2, mode: 2, looseness: 70 } },
  { file: 'physical-defaults-seed2-120bpm.mid', bpm: 120, params: { seed: 2, mode: 3 } },
];

function renderExample(ex) {
  const E = require('../engine');
  const { writeMidi } = require('../cli/lib/midifile');
  const eng = E.createEngine({ params: ex.params, bpm: ex.bpm });
  eng.reset(0);
  const notes = eng.generate(0, 32 * eng.meter.barLen);
  return Buffer.from(writeMidi({ notes, bpm: ex.bpm, meter: eng.meter, name: ex.file.replace(/\.mid$/, '') }));
}

function main(argv) {
  if (argv.includes('--artifact')) {
    // Body fragment for publishing the preview as a claude.ai Artifact.
    const file = path.join(ROOT, 'out', 'artifact', 'organic-groove-lab.html');
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, previewPage(false));
    process.stderr.write(`wrote ${path.relative(ROOT, file)}\n`);
    return;
  }
  const out = buildAll();
  const check = argv.includes('--check');
  let stale = 0;
  for (const rel of Object.keys(out)) {
    const file = path.join(ROOT, rel);
    const data = out[rel];
    const current = fs.existsSync(file) ? fs.readFileSync(file) : null;
    const same = current && Buffer.compare(current, Buffer.from(data)) === 0;
    if (check) {
      if (!same) {
        stale++;
        process.stderr.write(`stale: ${rel}\n`);
      }
    } else if (!same) {
      fs.writeFileSync(file, data);
      process.stderr.write(`wrote ${rel}\n`);
    }
  }
  if (check && stale) {
    process.stderr.write('run `npm run build`\n');
    process.exit(1);
  }
}

if (require.main === module) main(process.argv.slice(2));

module.exports = { buildAll, previewPage };
